// POC 2: writes app/poc2-own.css, the classes of the wider closed lists: 16 font families (the CSS stacks live ONLY here, never in a stored
// document), the 72-name palette of look (b), the two classes that carry a validated #rrggbb value of look (c) through a custom property,
// and the marks the proof draws for check boxes and embedded files.
import { writeFileSync } from "node:fs";
import { PALETTE_72 } from "../lib/poc2Look.mjs";

const STACKS = {
  SANS_NEUTRAL: 'Arial, Helvetica, "Liberation Sans", sans-serif',
  SANS_HUMANIST: 'Calibri, Carlito, "Segoe UI", sans-serif',
  SANS_WIDE: "Verdana, Tahoma, sans-serif",
  SANS_FRIENDLY: '"Trebuchet MS", sans-serif',
  SANS_UNICODE: '"Arial Unicode MS", Arial, sans-serif',
  DISPLAY_HEAVY: '"Arial Black", "Helvetica Neue", Arial, sans-serif',
  DISPLAY_IMPACT: 'Impact, "Arial Narrow", sans-serif',
  SERIF_TEXT: '"Times New Roman", Times, "Liberation Serif", serif',
  SERIF_SCREEN: "Georgia, serif",
  SERIF_SLAB: "Cambria, Caladea, Georgia, serif",
  MONO_CLASSIC: '"Courier New", Courier, monospace',
  MONO_CODE: 'Consolas, "Lucida Console", monospace',
  SANS_UI: "system-ui, sans-serif",
  SANS: "sans-serif",
  SERIF: "serif",
  MONO: "monospace",
};
const hex = (rgb) => "#" + rgb.map((v) => v.toString(16).padStart(2, "0")).join("");
let css = "/* generated by scripts/poc2-gen-css.mjs (POC 2). The font stacks are the only place a font name is written. */\n";
for (const [k, v] of Object.entries(STACKS)) css += `.pc2-ff-${k} { font-family: ${v}; }${k.startsWith("DISPLAY") ? ` .pc2-ff-${k} { font-weight: 800; }` : ""}\n`;
for (const p of PALETTE_72) css += `.pc2-b-bg-${p.name} { background: ${hex(p.rgb)}; } .pc2-b-tx-${p.name} { color: ${hex(p.rgb)}; }\n`;
css += `/* look (c): the value was checked as #rrggbb before it was handed to the page, and arrives as a custom property set through the CSS object model */\n`;
css += `.pc2-bgv { background-color: var(--pc2-bg); } .pc2-txv { color: var(--pc2-tx); }\n`;
css += `.pc2-ink-dark { color: #15202b; } .pc2-ink-light { color: #ffffff; }\n`;
css += `.pc2-tabs { display: flex; gap: 2px; margin: 0 0 var(--space-2); flex-wrap: wrap; } .pc2-tab { padding: var(--space-1) var(--space-3); border: 1px solid var(--color-border-strong); background: var(--color-surface-sunken); color: var(--color-text); cursor: pointer; font: var(--font-size-sm) var(--font-sans); }\n`;
css += `.pc2-tab[aria-selected="true"] { background: var(--color-surface); border-bottom-color: var(--color-surface); font-weight: 700; }\n`;
css += `.pc2-box { font-family: var(--font-sans); } .pc2-attach { outline: 1px dashed var(--color-accent); outline-offset: -3px; }\n`;
writeFileSync(new URL("../app/poc2-own.css", import.meta.url), css);
console.log(`app/poc2-own.css written, ${css.split("\n").length} lines`);
