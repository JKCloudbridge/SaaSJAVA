package app.platform.publicapi.internal;

import app.platformapi.ApiHeaders;
import app.platformapi.ApiPaths;
import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.headers.Header;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.media.Content;
import io.swagger.v3.oas.models.media.MediaType;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import io.swagger.v3.oas.models.responses.ApiResponse;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.tags.Tag;
import java.util.List;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springdoc.core.customizers.OperationCustomizer;
import org.springframework.boot.context.properties.EnableConfigurationProperties;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Wiring of the public API (Sprint 30): its settings, its version registry and the customizers that shape its contract
 * document (ADR-0248). The document is generated by pointing the generator at the public prefix (the contract tests
 * start an instance for it), committed, and served as committed. It names no host and no time, so it is the same on
 * every machine and can be compared like the internal one.
 */
@Configuration
@EnableConfigurationProperties(PublicApiProperties.class)
class PublicApiConfiguration {

    static final String BEARER = "bearerAuth";
    private static final String PUBLIC_MODULE = "app.platform.publicapi.";
    private static final String ERROR_SCHEMA = "ApiErrorResponse";

    @Bean
    ApiVersioning apiVersioning() {
        return ApiVersioning.shipped();
    }

    /**
     * Every operation of the public API can fail in the ways that do not depend on it, and says so. A customizer of
     * the generator applies to every document, so it acts only on the handlers of this module.
     */
    @Bean
    OperationCustomizer publicCommonStatuses() {
        return (operation, handlerMethod) -> {
            if (!handlerMethod.getBeanType().getName().startsWith(PUBLIC_MODULE)) {
                return operation;
            }
            boolean description = handlerMethod.getBeanType() == PublicOpenApiController.class;
            if (!description) {
                add(operation, "401", "No valid bearer token was sent, or it has expired or was revoked.");
            }
            add(operation, "404", "The organization, object or record does not exist, or the caller may not know that "
                    + "it exists. The three answer alike. Also the answer of every address when the public API is "
                    + "switched off.");
            add(operation, "429", "The organization has too many requests in progress. Try again after the number "
                    + "of seconds in the Retry-After header.");
            add(operation, "500", "An unexpected failure. Nothing about the cause is disclosed; quote the request ID.");
            add(operation, "503", "A dependency of the service is unavailable. Try again after the Retry-After "
                    + "header, or later.");
            return operation;
        };
    }

    private static void add(Operation operation, String status, String description) {
        if (operation.getResponses().containsKey(status)) {
            return;
        }
        Schema<?> reference = new Schema<>().$ref("#/components/schemas/" + ERROR_SCHEMA);
        operation.getResponses().addApiResponse(status, new ApiResponse().description(description)
                .content(new Content().addMediaType("application/json", new MediaType().schema(reference))));
    }

    /**
     * The title, the way to sign in, the headers every answer carries and the deprecations of the public contract. It
     * acts only on a document that holds the public addresses, which is the one the contract tests generate (the
     * generator is pointed at the public prefix); the internal document holds none and is left as it is.
     */
    @Bean
    OpenApiCustomizer publicContractDocument(ApiVersioning versioning) {
        return openApi -> {
            if (openApi.getPaths() == null || openApi.getPaths().keySet().stream()
                    .noneMatch(ApiPaths::isPublicApiPath)) {
                return;
            }
            openApi.setInfo(new Info()
                    .title("Public API")
                    .version("v1")
                    .description("The public API of the platform: create, read, change, delete, restore, query and "
                            + "bulk-write the records of the objects of an organization, for the software of that "
                            + "organization. Standard and custom objects are used in exactly the same way. Every "
                            + "successful body is {\"data\": ...} (a page adds \"pagination\"); every failure is "
                            + "{\"error\": {code, message, fields?, requestId, traceId?}}; branch on the code, "
                            + "never on the message. Inside version v1 a change only adds; a breaking change is a "
                            + "new version beside this one, and anything that is retired is announced at least 12 "
                            + "months before it goes. Who may see or change what is decided on every request by "
                            + "the permissions of the user the token belongs to, exactly as in the application."));
            Components components = openApi.getComponents() == null ? new Components() : openApi.getComponents();
            openApi.setComponents(components);
            components.addSecuritySchemes(BEARER, new SecurityScheme()
                    .type(SecurityScheme.Type.HTTP)
                    .scheme("bearer")
                    .description("The access token of a signed-in user, sent as `Authorization: Bearer <token>`. "
                            + "The organization is always the one the host name of the request names; a token "
                            + "never chooses it. Tokens for software itself (client credentials, scopes) are "
                            + "added by a later release; no static key exists or will."));
            openApi.addSecurityItem(new SecurityRequirement().addList(BEARER));
            openApi.setTags(List.of(
                    new Tag().name("Objects").description("Which objects exist for the caller, and their fields."),
                    new Tag().name("Records").description("Create, read, change, delete, restore, query and bulk."),
                    new Tag().name("Description").description("This document.")));
            openApi.getPaths().forEach((path, item) -> item.readOperationsMap().forEach((method, operation) -> {
                if (ApiPaths.PUBLIC_OPENAPI.equals(path)) {
                    operation.setSecurity(List.of());
                }
                versioning.deprecations().stream()
                        .filter(deprecation -> deprecation.method().equals(method.name())
                                && deprecation.template().equals(path))
                        .findFirst().ifPresent(deprecation -> operation.setDeprecated(true));
                if (operation.getResponses() != null) {
                    operation.getResponses().values().forEach(PublicApiConfiguration::addHeaders);
                }
            }));
        };
    }

    private static void addHeaders(ApiResponse response) {
        response.addHeaderObject(ApiHeaders.REQUEST_ID, new Header().description(
                "Identifies the request. Send your own (8 to 64 letters, digits, dot, underscore or hyphen) or "
                        + "one is made. Quote it when asking for support.").schema(new StringSchema()));
        response.addHeaderObject(ApiHeaders.API_VERSION, new Header().description(
                "The major version of the public API that answered.").schema(new StringSchema().example("v1")));
    }
}
